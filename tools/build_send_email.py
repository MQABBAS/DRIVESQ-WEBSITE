#!/usr/bin/env python3
"""Rebuilds the generated part of supabase/functions/send-email/index.ts:
   - the email designer (THEMES, BANNERS, build, text, personalise) copied from admin.html (DSQM module)
   - the weekly-reminder topics (STANDING, FOCUS) copied from admin.html (DSQ-AUTOMAIL module)
   - the Monday instructor emails from supabase/functions/send-email/monday.part.js
Run after changing any of those, then paste index.ts into Supabase → Edge Functions → send-email → Deploy."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
adm = open(os.path.join(ROOT, "admin.html"), encoding="utf-8").read().split("\n")
def block(start_pred, end_pred):
    s = next(i for i, l in enumerate(adm) if start_pred(l))
    e = next(i for i in range(s + 1, len(adm)) if end_pred(adm[i]))
    return "\n".join(adm[s:e])
tpl = block(lambda l: l.strip() == 'var ASSET = "https://www.drivesq.co.uk/email/";', lambda l: '"Create a template for me"' in l)
topics = block(lambda l: l.startswith("  const STANDING = "), lambda l: l.startswith("  const weekStart = () =>"))
part = open(os.path.join(ROOT, "supabase/functions/send-email/monday.part.js"), encoding="utf-8").read()
gen = ("// ==== GENERATED by tools/build_send_email.py — edit admin.html / monday.part.js, not here ==== START\n"
       "const { build, text, personalise } = (function () {\n" + tpl + "\n  return { build: build, text: text, personalise: personalise };\n})();\n"
       "const { STANDING, FOCUS } = (function () {\n" + topics + "\n  return { STANDING, FOCUS };\n})();\n"
       + part + "\n// ==== GENERATED ==== END\n")
p = os.path.join(ROOT, "supabase/functions/send-email/index.ts")
src = open(p, encoding="utf-8").read()
if "==== GENERATED" in src:
    src = re.sub(r"// ==== GENERATED by tools/build_send_email\.py.*?// ==== GENERATED ==== END\n", lambda m: gen, src, flags=re.S)
else:
    src = src.replace("\nserve(async (req) => {", "\n" + gen + "\nserve(async (req) => {", 1)
open(p, "w", encoding="utf-8").write(src)
print("index.ts:", len(src.split("\n")), "lines")
